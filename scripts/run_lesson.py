"""Replay the lesson against the lab database: plan before, one change, plan after, write cost per index.

Every plan is captured twice and the second run is kept, so the first (cold cache) run does not
distort the timing. Plans are written next to their query in sql/explain/, the numbers to
sql/explain/results.md.
"""
import lab

CAPTURES_BEFORE_ANY_INDEX = [
    "q1_day_before", "q2_latest_whale_before", "q2_latest_small_before", "q3_toast_wide", "q3_toast_narrow",
]
STEPS = [  # (migration number, index it adds, plans captured once it exists)
    (1, "idx_orders_created_at", ["q1_day_after"]),
    (2, "idx_orders_customer_created", ["q2_latest_whale_after", "q2_latest_small_after", "q3_listing_before", "q3_listing_narrow"]),
    (3, "idx_orders_listing", ["q3_listing_after"]),
    (4, "idx_orders_listing only (idx_orders_customer_created dropped)", []),
]


def capture(connection, name, results):
    path = lab.EXPLAIN_DIR / f"{name}.sql"
    lab.plan_lines(connection, path)                       # warm-up run, discarded
    lines = lab.plan_lines(connection, path)
    (lab.EXPLAIN_DIR / f"{name}.txt").write_text("\n".join(lines) + "\n")
    results[name] = {"ms": lab.execution_ms(lines), "buffers": lab.buffers_touched(lines), "lines": lines}
    print(f"{name:26} {results[name]['ms']:10.3f} ms {results[name]['buffers']:8} buffers")


def main():
    results, write_cost = {}, {}
    with lab.connect() as connection:
        rows_before = lab.row_count(connection)
        lab.reset_to(connection, 0)
        print("== Plans before any index ==")
        for name in CAPTURES_BEFORE_ANY_INDEX:
            capture(connection, name, results)
        write_cost["no new indexes"] = lab.measure_write_cost()
        print("== Add one index at a time, read the new plan, measure the write cost ==")
        for number, label, names in STEPS:
            lab.run_file(connection, lab.MIGRATIONS[number - 1])
            connection.execute("ANALYZE orders")
            for name in names:
                capture(connection, name, results)
            write_cost["+ " + label if number < 4 else label] = lab.measure_write_cost()
            connection.execute("VACUUM orders")
        index_sizes = connection.execute(
            "SELECT indexrelname, pg_relation_size(indexrelid) FROM pg_stat_user_indexes "
            "WHERE relname = 'orders' ORDER BY indexrelname").fetchall()
        assert lab.row_count(connection) == rows_before, "write-cost batches must be rolled back"
    write_results(results, write_cost, index_sizes)
    print("== Write cost of 10,000 inserts (median of 5, rolled back) ==")
    for label, cost in write_cost.items():
        print(f"{label:62} {cost['milliseconds']:8.1f} ms {cost['buffers']:8.0f} pages {cost['wal_records']:8.0f} WAL records")


def write_results(results, write_cost, index_sizes):
    pairs = [("q1_day", "q1_day_before", "q1_day_after"),
             ("q2 latest 10, heavy customer", "q2_latest_whale_before", "q2_latest_whale_after"),
             ("q2 latest 10, small customer", "q2_latest_small_before", "q2_latest_small_after"),
             ("q3 listing: SELECT * vs covering index", "q3_listing_before", "q3_listing_after"),
             ("q3 listing: five columns, no covering index", "q3_listing_before", "q3_listing_narrow"),
             ("q3 TOAST demo: SELECT * vs without the note", "q3_toast_wide", "q3_toast_narrow")]
    out = ["# Results of the last `make run`", "",
           "Generated by `scripts/run_lesson.py`; the plans are the `.txt` files next to each `.sql` here.", "",
           "| Query | Before ms | After ms | Faster | Before buffers | After buffers |", "|---|---:|---:|---:|---:|---:|"]
    for label, before, after in pairs:
        b, a = results[before], results[after]
        out.append(f"| {label} | {b['ms']:.3f} | {a['ms']:.3f} | {b['ms'] / a['ms']:.0f}x | {b['buffers']} | {a['buffers']} |")
    out += ["", "## Write cost of one batch of 10,000 inserts", "",
            "Median of 5 runs after a warm-up, each rolled back. Pages touched and WAL records are the stable numbers",
            "(each index adds about 10,000 of each); milliseconds and WAL bytes vary with the machine and with full-page images.", "",
            "| Index set | Median ms | Pages touched | WAL records | WAL MB |", "|---|---:|---:|---:|---:|"]
    out += [f"| {label} | {cost['milliseconds']:.1f} | {cost['buffers']:.0f} | {cost['wal_records']:.0f} | {cost['wal_bytes'] / 1e6:.1f} |"
            for label, cost in write_cost.items()]
    out += ["", "## Index sizes at the end", "", "| Index | Size MB |", "|---|---:|"]
    out += [f"| {name} | {size / 1e6:.1f} |" for name, size in index_sizes]
    (lab.EXPLAIN_DIR / "results.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
